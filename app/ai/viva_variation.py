    ('Accuracy', ('How would you check whether an explanation of {topic} is correct?', 'What criteria would you use to verify a claim about {topic}?', 'Explain how to test understanding of {topic} against course material.')),
    ('Cause and effect', ('What causes or influences the outcome related to {topic}?', 'Explain an important cause-and-effect relationship in {topic}.', 'How does changing a relevant condition affect the use of {topic}?')),
    ('Breakdown', ('Divide {topic} into its main parts or components.', 'What elements make up {topic} and how do they interact?', 'Explain the major components involved in {topic}.')),
    ('Decision', ('How would you decide between {topic} and a related idea?', 'What questions would you ask before choosing to apply {topic}?', 'Describe a reasoned choice involving the use of {topic}.')),
    ('Reformulation', ('Restate {topic} as a short question and answer it.', 'Explain {topic} from a different perspective while keeping its meaning.', 'Rephrase the main concept of {topic} without changing the facts.')),
